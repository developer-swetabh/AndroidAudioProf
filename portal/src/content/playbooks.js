function ask(q, why, dump, look, lkg, { yes, no }) {
  return { type: "ask", q, why, dump, dumps: dump ? [dump] : [], look, lkg, yes, no };
}

function collect(q, why, dumps, look, lkg, next) {
  return { type: "collect", q, why, dump: dumps[0], dumps, look, lkg, next };
}

function verdict(title, owner, domain, rca, learn, scenario) {
  return { type: "verdict", title, owner, domain, rca, learn, scenario };
}

export function getPlaybook(id) {
  return PLAYBOOKS.find((p) => p.id === id) || PLAYBOOKS[0];
}

export function getNode(id) {
  return NODES[id] || VERDICTS[id] || null;
}
